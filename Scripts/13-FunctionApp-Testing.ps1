dotnet run

# ==========================================
# 2. Re-establish Azure SQL Administrator Connection
# ==========================================

# Close and dispose the previous SQL connection if it exists.
if ($Connection) {
    $Connection.Close()
    $Connection.Dispose()
}

# Retrieve the SQL Administrator connection details from Key Vault.
$KeyVaultName = "kv-lab02-dev-09"

$PasswordSecret = Get-AzKeyVaultSecret `
    -VaultName $KeyVaultName `
    -Name "SqlAdminPassword"

# Convert the retrieved SecureString password into plain text.
$SqlPassword = [System.Net.NetworkCredential]::new(
    "",
    $PasswordSecret.SecretValue
).Password

# Rebuild the SQL Administrator connection string.
$SqlServerName = "sqlserver-azlab02-dev-09"
$DatabaseName = "sqldb-lab02-dev"

$ConnectionString = "Server=tcp:$SqlServerName.database.windows.net,1433;Initial Catalog=$DatabaseName;User ID=sqladminuser;Password=$SqlPassword;Encrypt=True;TrustServerCertificate=False;Connection Timeout=30;"

# Create a new SQL connection.
$Connection = New-Object System.Data.SqlClient.SqlConnection($ConnectionString)

# Open the connection to Azure SQL Database.
$Connection.Open()

# Clear the temporary plaintext password variable.
$SqlPassword = $null
$PasswordSecret = $null

Write-Host "SQL Administrator connection established successfully."

# ==========================================
# 3. Verify Inventory After Order Submission
# ==========================================

# Create a SQL command using the established Administrator connection.
$Command = $Connection.CreateCommand()

# Retrieve the current inventory details for LAPTOP-001.
$Command.CommandText = "SELECT ProductId, ProductName, AvailableQuantity, UpdatedAt FROM dbo.Inventory WHERE ProductId = 'LAPTOP-001';"

# Execute the query and retrieve the result.
$Reader = $Command.ExecuteReader()

# Display the product information and its current available quantity.
while ($Reader.Read()) {
    [PSCustomObject]@{
        ProductId = $Reader["ProductId"]
        ProductName = $Reader["ProductName"]
        AvailableQuantity = $Reader["AvailableQuantity"]
        UpdatedAt = $Reader["UpdatedAt"]
    }
}

# Close the Data Reader after retrieving the results.
$Reader.Close()

